import assert from 'node:assert/strict';
import fs from 'node:fs';
import {randomUUID} from 'node:crypto';
const {PGlite}=await import(process.env.SWJ_PGLITE||'@electric-sql/pglite');
const db=new PGlite();
try{
 await db.exec(`CREATE ROLE anon;CREATE ROLE authenticated;CREATE ROLE service_role BYPASSRLS;
 GRANT USAGE ON SCHEMA public TO service_role,anon,authenticated;
 CREATE TABLE public.invoices(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,invnum text UNIQUE,data jsonb DEFAULT '{}');
 INSERT INTO invoices(invnum) VALUES ('2020131'),('2020131v4'),('DRAFT-AUDIT-20261104-1'),('GS999999999'),('FINANCE_CONFIG');
 GRANT SELECT ON invoices TO service_role;`);
 await db.exec(fs.readFileSync('sql/invoice_number_reservations.sql','utf8'));
 await db.exec('SET ROLE service_role');
 const reserve=async(id,wanted=null)=>(await db.query('SELECT public.reserve_invoice_number($1::uuid,$2::text) AS reservation',[id,wanted])).rows[0].reservation;
 const id=randomUUID();const first=await reserve(id);assert.equal(first.invnum,'2020132');assert.deepEqual(await reserve(id),first,'lost response retry returns same number');
 const rows=await Promise.all(Array.from({length:100},()=>reserve(randomUUID())));
 assert.equal(new Set(rows.map(r=>r.invnum)).size,100);assert.equal(rows[99].invnum,'2020232');
 await assert.rejects(reserve(randomUUID(),'2020131'),/already in use/);
 await assert.rejects(reserve(randomUUID(),'2020132'),/already in use/);
 await assert.rejects(reserve(randomUUID(),'DRAFT-20261234'),/numeric/);
 await assert.rejects(reserve(id,'2020999'),/changed/);
 const manual=await reserve(randomUUID(),'2021000');assert.equal(manual.invnum,'2021000');assert.equal((await reserve(randomUUID())).invnum,'2021001');
 assert.equal((await reserve(randomUUID(),'2020131v5')).invnum,'2020131v5');
 await db.exec('RESET ROLE');
 assert.equal((await db.query('SELECT count(*)::int AS count FROM invoices')).rows[0].count,5,'existing invoices are untouched');
 for(const role of ['anon','authenticated']){
  await db.exec('SET ROLE '+role);
  await assert.rejects(db.query('SELECT * FROM invoice_number_reservations'),/permission denied/);
  await assert.rejects(db.query('SELECT reserve_invoice_number($1::uuid)',[randomUUID()]),/permission denied/);
  await db.exec('RESET ROLE');
 }
 // Idempotent installer retains all reservations/state, never resets issued numbers.
 await db.exec(fs.readFileSync('sql/invoice_number_reservations.sql','utf8'));
 await db.exec('SET ROLE service_role');assert.equal((await reserve(randomUUID())).invnum,'2021002');
 console.log('PASS isolated PostgreSQL: 100 queued requests unique, retry idempotency, occupied/manual/revision checks, service-only access and unchanged existing invoices');
}finally{await db.close();}
